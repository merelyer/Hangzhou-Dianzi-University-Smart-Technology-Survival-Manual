def add_list(doc, items, style="List Bullet"):
    for item in items:
        doc.add_paragraph(item, style=style)


def write_doc(part):
    num = part["num"]
    title = f"第{num}讲 {part['title']} 复习文档"

    md_lines = [f"# {title}", "", part["source"], ""]
    doc = Document()
    styles = doc.styles
    styles["Normal"].font.name = "Microsoft YaHei"
    styles["Normal"].font.size = Pt(10.5)
    doc.add_heading(title, level=0)
    doc.add_paragraph(part["source"])

    all_sections = part["sections"] + extras.get(num, [])
    for heading, items in all_sections:
        doc.add_heading(heading, level=1)
        md_lines += [f"## {heading}", ""]
        add_list(doc, items)
        for item in items:
            md_lines.append(f"- {item}")
        md_lines.append("")

    md_path = OUT_DIR / f"第{num}讲_{part['title']}_复习文档.md"
    docx_path = OUT_DIR / f"第{num}讲_{part['title']}_复习文档.docx"
    md_path.write_text("\n".join(md_lines), encoding="utf-8")
    doc.save(docx_path)
    return md_path, docx_path


def main():
    written = []
    for part in doc_parts():
        written.append(write_doc(part))

    index_lines = ["# 自然语言处理 1-7讲复习文档索引", ""]
    index_doc = Document()
    index_doc.add_heading("自然语言处理 1-7讲复习文档索引", level=0)
    index_doc.add_paragraph("已按讲次生成独立复习文档。第6讲依据配套教材第4.4节与第7章整理，因为本地没有对应 PPTX。")
    for md_path, docx_path in written:
        index_lines.append(f"- {docx_path.name}")
        index_doc.add_paragraph(docx_path.name, style="List Bullet")
    (OUT_DIR / "README.md").write_text("\n".join(index_lines), encoding="utf-8")
    index_doc.save(OUT_DIR / "自然语言处理_1-7讲复习文档索引.docx")


if __name__ == "__main__":
    main()
