from docx.shared import Pt


OUT_PATH = Path("自然语言处理_课后习题精简答案.docx")


def set_font(run, size=12, bold=False):
    run.font.name = "宋体"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(size)
    run.bold = bold


def add_paragraph(doc, text="", size=12, bold=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_font(run, size=size, bold=bold)
    return p


def add_question(doc, question, answer):
    p = doc.add_paragraph()
    r1 = p.add_run("题目：")
    set_font(r1, bold=True)
    r2 = p.add_run(question)
    set_font(r2)

    p = doc.add_paragraph()
    r1 = p.add_run("答案：")
    set_font(r1, bold=True)
    r2 = p.add_run(answer)
    set_font(r2)

    doc.add_paragraph()


