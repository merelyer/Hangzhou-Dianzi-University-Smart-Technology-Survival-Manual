// 查找状态索引
static int find_state_index(const char* state_str) {
    for (int i = 0; i < 24; i++) {
        if (state_str_list[i][0] == state_str[0] && state_str_list[i][1] == state_str[1]) {
            return i;
        }
    }
    return -1;
}

// 编码状态
static int encode_state(const char* state_str, const bool l_arm, const bool r_arm) {
    int state_idx = find_state_index(state_str);
    if (state_idx == -1) {
        debug_print("未知的状态字符串: %s\n", state_str);
        return -1;
    }
    return (state_idx << 2) | (l_arm << 1) | r_arm;
}

// 解码状态
static void decode_state(const int8_t state_int, char* state_str, bool* l_arm, bool* r_arm) {
    int8_t state_idx = state_int >> 2;
    if (state_idx >= 24) {
        debug_print("未知的状态编码: %d\n", state_int);
        state_idx = 0;
    }
    *l_arm = (state_int >> 1) & 1;
    *r_arm = state_int & 1;
    state_str[0] = state_str_list[state_idx][0];
    state_str[1] = state_str_list[state_idx][1];
    state_str[2] = 0;
}

// 计算旋转操作的时间和状态变化
// output_sequence的长度至少为14
// 如果不需要返回字符串，可以设置os = 0
static int calculate_twist_time_and_state(const int8_t state_int, const char* action_str, 
                    int8_t* new_state_int, char* os) {
    char state_str[3];
    bool l_arm, r_arm;
    decode_state(state_int, state_str, &l_arm, &r_arm);
    
    char face = action_str[0];
    char modifier = action_str[1]; // 可能为'\0'、'\''或'2'

    int time_cost = 0;
    ArmSide arm_side;
    // 确定使用哪只手臂
    if (state_str[0] == face) {
        arm_side = LEFT;
    } else if (state_str[1] == face) {
        arm_side = RIGHT;
    } else {
        // debug_print("状态 %d (%s) 无法操作目标面 %c\n", state_int, state_str, face);
        return -1;
    }
    
    // 检查是否需要空转操作
    if (arm_side == LEFT && r_arm) {
        if(os) strcat(os, "R2 R+N R0 ");
        time_cost += ARM_BACK;
        r_arm = false;
    } else if (arm_side == RIGHT && l_arm) {
        if(os) strcat(os, "L2 L+N L0 ");
        time_cost += ARM_BACK;
        l_arm = false;
    }

    // 根据修饰符确定旋转类型
    if (arm_side == LEFT) {
        if (modifier == '\'') {  // 逆时针90°
            if(os) strcat(os, "L-T ");
            time_cost += ROTATE_90;
            l_arm = !l_arm;
        } else if (modifier == '2') {  // 180°
            if(os) strcat(os, "L*T ");
            time_cost += ROTATE_180;
        } else {  // 顺时针90°
            if(os) strcat(os, "L+T ");
            time_cost += ROTATE_90;
            l_arm = !l_arm;
        }
    } else {  // 右臂操作
        if (modifier == '\'') {  // 逆时针90°
            if(os) strcat(os, "R-T ");
            time_cost += ROTATE_90;
            r_arm = !r_arm;
        } else if (modifier == '2') {  // 180°
            if(os) strcat(os, "R*T ");
            time_cost += ROTATE_180;
        } else {  // 顺时针90°
            if(os) strcat(os, "R+T ");
            time_cost += ROTATE_90;
            r_arm = !r_arm;
        }
    }

    *new_state_int = encode_state(state_str, l_arm, r_arm);
    return time_cost;
}

