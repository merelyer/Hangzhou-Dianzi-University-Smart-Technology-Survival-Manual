def write_docx(path: Path, markdown_text: str) -> None:
    doc = Document()
    styles = doc.styles
    for style_name in ["Normal", "Heading 1", "Heading 2", "Heading 3"]:
        style = styles[style_name]
        style.font.name = "Microsoft YaHei"
        style._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei")
    styles["Normal"].font.size = Pt(10.5)

    for raw in markdown_text.splitlines():
        line = raw.rstrip()
        if not line:
            continue
        if line.startswith("# "):
            doc.add_heading(line[2:], level=1)
        elif line.startswith("## "):
            doc.add_heading(line[3:], level=2)
        elif line.startswith("### "):
            doc.add_heading(line[4:], level=3)
        elif re.match(r"^\d+\.\s+", line):
            doc.add_paragraph(re.sub(r"^\d+\.\s+", "", line), style="List Number")
        elif line.startswith("- "):
            doc.add_paragraph(line[2:], style="List Bullet")
        else:
            doc.add_paragraph(line)
    doc.save(path)


def lecture_no(stem: str) -> str:
    return stem.split("_", 1)[0].lstrip("0")


def clean_page_text(text: str, title_hint: str) -> str:
    text = text.replace("\x00", "")
    lines = []
    seen = set()
    noise = [
        "杭州电子科技大学",
        "HANGZHOU DIANZI UNIVERSITY",
        "电子科技大学",
        "ww@hdu.edu.cn",
        "吴炜",
        "吴 微",
    ]
    title_plain = title_hint.replace("_复习文档", "").replace("_", "")
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if any(x in line for x in noise):
            continue
        if re.fullmatch(r"第\s*\d+\s*页", line):
            continue
        if line.replace("_中文讲义", "").replace("_", "") in title_plain:
            continue
        if line in seen:
            continue
        seen.add(line)
        lines.append(line)
    return "\n".join(lines).strip()


def build_page_appendix(stem: str) -> str:
    if not EXTRACTED.exists():
        return ""
    no = lecture_no(stem)
    matches = sorted(EXTRACTED.glob(f"{no}.*_中文讲义.txt"))
    if not matches:
        return ""

    text = matches[0].read_text(encoding="utf-8", errors="ignore")
    text = text.replace("\x00", "")
    parts = re.split(r"=====.*?(\d+).*?=====", text)
    page_pairs = []
    if len(parts) > 1:
        for i in range(1, len(parts), 2):
            page_no = parts[i]
            body = parts[i + 1] if i + 1 < len(parts) else ""
            cleaned = clean_page_text(body, stem)
            if cleaned:
                page_pairs.append((page_no, cleaned))
    else:
        cleaned = clean_page_text(text, stem)
        if cleaned:
            page_pairs.append(("全文", cleaned))

    if not page_pairs:
        return ""

    appendix = ["\n## 课件逐页要点速查"]
    appendix.append("这一部分来自讲义 PDF 的逐页文字抽取，已过滤重复页眉页脚。复习时可先看前面的框架，再用这里对照课件细节。")
    for page_no, body in page_pairs:
        appendix.append(f"\n### 第 {page_no} 页")
        appendix.append(body)
    return "\n".join(appendix) + "\n"


